export const initialen = (s: string) =>
  s
    .split(/\s+/)
    .filter(Boolean)
    .slice(0, 2)
    .map((w) => w[0]!.toUpperCase())
    .join("") || "?";

/** WhatsApp-link voor een NL-nummer. */
export function waLink(tel: string | null): string | null {
  const d = tel?.replace(/[^\d+]/g, "").replace(/^\+/, "").replace(/^00/, "").replace(/^0(?=\d{9}$)/, "31");
  return d && d.length >= 10 ? `https://wa.me/${d}` : null;
}
